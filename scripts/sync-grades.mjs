// Copies Civic's grade eligibility into the repo (build-time). Fail closed: no file -> {present:false} -> no grades.
// Usage: node scripts/sync-grades.mjs [path]   (default: /workspace/townhall/civic/grades_eligibility.json,
// falling back to /workspace/townhall/civic/grade_races.json; a {races:[ids]} file lists eligible race ids).
import fs from "node:fs";
import { eligibleSet } from "../lib/grades.mjs";
const cands = process.argv[2] ? [process.argv[2]] : ["/workspace/townhall/civic/grades_eligibility.json", "/workspace/townhall/civic/grade_races.json"];
const src = cands.find((p) => fs.existsSync(p));
let gen = { present: false, source: null, data: null };
if (src) {
  const data = JSON.parse(fs.readFileSync(src, "utf8"));
  const dest = `data/civic/${src.split("/").pop()}`;
  fs.writeFileSync(dest, JSON.stringify(data, null, 1) + "\n");
  // Only the eligible ids ship in the client bundle (not Civic's 97 KB of reasons).
  gen = { present: true, source: dest, data: { races: [...eligibleSet(data)].sort() } };
  console.log(`copied ${src} -> ${dest}; ${gen.data.races.length} eligible races`);
} else console.log("no Civic grade eligibility file: grades stay off (fail closed)");
fs.writeFileSync("lib/gradesEligibility.gen.mjs", `// Generated by scripts/sync-grades.mjs. Do not edit. Fail closed: present false = no grades.\nexport default ${JSON.stringify(gen)};\n`);
